#!/usr/bin/env python3
import argparse
import csv
import json
import os
import shlex
import subprocess
import sys
import time
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Tuple

SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_DATASET_ROOT = SCRIPT_DIR.parent
DEFAULT_HOST_RESULTS_MOUNT = Path("/mnt/femu-host-results")

# bb_flip cdw10 values (must match ftl.h enum)
FEMU_STATS_RESET = 8
FEMU_STATS_DUMP  = 9


VALID_MEASURES = {"short", "long", "both", "auto"} # For --measure
CAP_DIR_MAP = { # For --cap
    "none": "fio_iolog",
    "10": "fio_iolog_cap_10ms", # 10ms capped
    "50": "fio_iolog_cap_50ms", # 50ms capped
}


@dataclass(frozen=True)
class WorkloadUnit:
    unit: str  # For --unit. This is the unit name. e.g. "msr_hm_0"
    warmup: Path
    short: Optional[Path]
    long: Optional[Path]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Run a workload tier with a fill step, warmup, and selected measured replay "
            "segments using fio iologs."
        )
    )
    parser.add_argument("tier", help="Tier directory under the dataset root, e.g. core or long_gc.")
    parser.add_argument("scheme", help="Scheme name used in result file names.")
    parser.add_argument(
        "--target",
        default=os.environ.get("TARGET", ""),
        help="Block device target. Defaults to TARGET env var.",
    )
    parser.add_argument(
        "--measure",
        choices=sorted(VALID_MEASURES),
        default="auto",
        help="Which measured segment to run after warmup.", # short or long or both or auto
    )
    parser.add_argument(
        "--cap",
        choices=sorted(CAP_DIR_MAP), # none, 10, 50
        default="10",
        help="Which iolog family to use: uncapped, 10 ms capped, or 50 ms capped.",
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=DEFAULT_DATASET_ROOT,
        help="Dataset root. Defaults to the workload_sets directory containing this script.",
    )
    parser.add_argument(
        "--unit",
        action="append",
        default=[],
        help="Only run this workload unit. Can be repeated.",
    )
    parser.add_argument(
        "--fill-size",
        default=os.environ.get("FILL_SIZE", "70%"),
        help="Device percentage to pre-fill with fio randwrite before each unit.",
    )
    parser.add_argument(
        "--fill-bs",
        default=os.environ.get("FILL_BS", "256k"),
        help="Block size for the fill workload.",
    )
    parser.add_argument(
        "--fill-iodepth",
        default=os.environ.get("FILL_IODEPTH", "8"),
        help="Iodepth for the fill workload.",
    )
    parser.add_argument(
        "--replay-time-scale",
        default=os.environ.get("REPLAY_TIME_SCALE", "100"),
        help="fio replay_time_scale for warmup and measured runs.",
    )
    parser.add_argument(
        "--ioengine",
        default=os.environ.get("IOENGINE", "libaio"),
        help="fio ioengine for replay.",
    )
    parser.add_argument(
        "--iodepth",
        default=os.environ.get("IODEPTH", "1"),
        help="fio iodepth for replay.",
    )
    parser.add_argument(
        "--results-dir",
        type=Path,
        default=None,
        help="Optional override for results directory.",
    )
    parser.add_argument(
        "--write-lat-log",
        dest="write_lat_log",
        action="store_true",
        help="Write fio latency logs for measured phases. Enabled by default.",
    )
    parser.add_argument(
        "--no-write-lat-log",
        dest="write_lat_log",
        action="store_false",
        help="Disable fio latency logs for measured phases.",
    )
    parser.add_argument(
        "--log-avg-msec",
        default="10",
        help="fio log_avg_msec value used with --write-lat-log. Default: 10.",
    )
    parser.add_argument(
        "--repetition-id",
        default="0",
        help="Opaque repetition identifier recorded in metadata.",
    )
    parser.add_argument(
        "--build-label",
        default=os.environ.get("BUILD_LABEL", ""),
        help="Opaque emulator/build label recorded in metadata.",
    )
    parser.add_argument(
        "--skip-fill",
        action="store_true",
        help="Skip the randwrite pre-fill step.",
    )
    parser.add_argument(
        "--skip-warmup",
        action="store_true",
        help="Skip warmup replay and only run measured segments.",
    )
    parser.add_argument(
        "--scaled",
        action="store_true",
        help="Use address-scaled iolog directories (generated by scale_iologs.py).",
    )
    parser.add_argument(
        "--ssd-size-mb",
        default=os.environ.get("SSD_SIZE_MB", "12288"),
        help="SSD size in MiB used as the scaling target. Must match the suffix of the "
             "scaled iolog directories (e.g. 12288 -> fio_iolog_cap_10ms_scaled_12288mb). "
             "Default: 12288.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print commands without executing fio.",
    )
    parser.add_argument(
        "--nvme-dev",
        default=os.environ.get("NVME_DEV", "/dev/nvme0"),
        help="NVMe device used to send FEMU flip (stats reset/dump) commands. "
             "Default: /dev/nvme0 or NVME_DEV env var.",
    )
    parser.add_argument(
        "--run-id-base",
        type=int,
        default=None,
        help="Base integer for run IDs passed to FEMU stats dump (cdw11). "
             "Each measured phase increments this by 1. "
             "Defaults to current Unix timestamp truncated to 20 bits.",
    )
    parser.add_argument(
        "--no-femu-stats",
        action="store_true",
        help="Skip sending FEMU stats reset/dump flip commands (for non-FEMU targets).",
    )
    parser.add_argument(
        "--host-results-mount",
        type=Path,
        default=Path(os.environ.get("HOST_RESULTS_MOUNT", str(DEFAULT_HOST_RESULTS_MOUNT))),
        help="Guest mountpoint for the host-shared results directory. "
             "If mounted and --results-dir is unset, results are written there.",
    )
    parser.set_defaults(write_lat_log=True)
    return parser.parse_args()


def resolve_measure(tier: str, measure: str) -> List[str]:
    if measure == "auto":
        return ["long"] if tier == "long_gc" else ["short"]
    if measure == "both":
        return ["short", "long"]
    return [measure]


def run(
    cmd: List[str],
    dry_run: bool,
    env: Optional[Dict[str, str]] = None,
    stdout_path: Optional[Path] = None,
) -> None:
    print("+", " ".join(shlex.quote(part) for part in cmd), flush=True)
    if dry_run:
        return
    if stdout_path is not None:
        stdout_path.parent.mkdir(parents=True, exist_ok=True)
        with stdout_path.open("w", encoding="utf-8") as f:
            subprocess.run(cmd, check=True, env=env, stdout=f, stderr=subprocess.STDOUT)
        return
    subprocess.run(cmd, check=True, env=env)


def discover_units(iolog_dir: Path) -> List[WorkloadUnit]:
    mapping: Dict[str, Dict[str, Path]] = {}
    for path in sorted(iolog_dir.glob("*.iolog")):
        stem = path.stem
        if "__" not in stem:
            continue
        unit, segment = stem.split("__", 1)
        mapping.setdefault(unit, {})[segment] = path

    units: List[WorkloadUnit] = []
    for unit in sorted(mapping):
        segments = mapping[unit]
        warmup = segments.get("warmup")
        if warmup is None:
            continue
        units.append(
            WorkloadUnit(
                unit=unit,
                warmup=warmup,
                short=segments.get("normal_short"),
                long=segments.get("normal_long"),
            )
        )
    return units


def append_summary(
    summary_csv: Path,
    scheme: str,
    tier: str,
    unit: str,
    phase: str,
    iolog_path: Path,
    json_path: Optional[Path],
    femu_run_id: Optional[int] = None,
) -> None:
    summary_csv.parent.mkdir(parents=True, exist_ok=True)
    write_header = not summary_csv.exists()
    with summary_csv.open("a", newline="", encoding="utf-8") as f:
        writer = csv.writer(f)
        if write_header:
            writer.writerow(
                ["timestamp", "scheme", "tier", "unit", "phase", "iolog_path", "json_path",
                 "femu_run_id"]
            )
        writer.writerow(
            [
                datetime.now().isoformat(timespec="seconds"),
                scheme,
                tier,
                unit,
                phase,
                str(iolog_path),
                "" if json_path is None else str(json_path),
                "" if femu_run_id is None else str(femu_run_id),
            ]
        )


def write_metadata(path: Path, payload: dict) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def femu_flip(dev: str, cdw10: int, cdw11: int = 0, dry_run: bool = False) -> None:
    """Send a FEMU bb_flip admin command from inside the guest VM."""
    cmd = [
        "nvme", "admin-passthru", dev,
        f"--opcode=0xef",
        f"--cdw10={cdw10}",
        f"--cdw11={cdw11}",
        "-n", "0",
    ]
    print("+", " ".join(shlex.quote(part) for part in cmd), flush=True)
    if dry_run:
        return
    try:
        subprocess.run(cmd, check=True)
    except subprocess.CalledProcessError as exc:
        print(f"warning: femu_flip failed (cdw10={cdw10} cdw11={cdw11}): {exc}",
              file=sys.stderr)


def fio_fill_cmd(args: argparse.Namespace) -> List[str]:
    return [
        "fio",
        "--name=device_fill",
        f"--filename={args.target}",
        "--ioengine=libaio",
        "--direct=1",
        "--thread=1",
        "--rw=randwrite",
        f"--bs={args.fill_bs}",
        f"--iodepth={args.fill_iodepth}",
        "--numjobs=1",
        "--invalidate=1",
        "--norandommap=1",
        "--randrepeat=0",
        "--time_based=0",
        "--group_reporting=1",
        f"--size={args.fill_size}",
    ]


def fio_replay_cmd(
    args: argparse.Namespace,
    job_name: str,
    iolog_path: Path,
    json_path: Optional[Path],
    lat_log_prefix: Optional[Path],
) -> List[str]:
    cmd = [
        "fio",
        f"--name={job_name}",
        f"--ioengine={args.ioengine}",
        f"--iodepth={args.iodepth}",
        "--direct=1",
        "--thread=1",
        f"--replay_time_scale={args.replay_time_scale}",
        f"--read_iolog={iolog_path}",
        f"--replay_redirect={args.target}",
    ]
    if lat_log_prefix is not None:
        cmd.extend(
            [
                f"--write_lat_log={lat_log_prefix}",
                f"--log_avg_msec={args.log_avg_msec}",
            ]
        )
    if json_path is not None:
        cmd.extend(["--output-format=json", f"--output={json_path}"])
    return cmd


def iter_phases(unit: WorkloadUnit, measures: Iterable[str]) -> List[Tuple[str, Path]]:
    phase_paths: List[Tuple[str, Path]] = []
    for measure in measures:
        if measure == "short" and unit.short is not None:
            phase_paths.append(("normal_short", unit.short))
        elif measure == "long" and unit.long is not None:
            phase_paths.append(("normal_long", unit.long))
    return phase_paths


def main() -> int:
    args = parse_args()
    if not args.target:
        print("missing target device; pass --target or set TARGET", file=sys.stderr)
        return 1

    root = args.root.resolve()
    cap_dir_name = CAP_DIR_MAP[args.cap]
    if args.scaled:
        cap_dir_name = f"{cap_dir_name}_scaled_{args.ssd_size_mb}mb"
    iolog_dir = root / args.tier / cap_dir_name
    if not iolog_dir.is_dir():
        print(f"missing iolog directory: {iolog_dir}", file=sys.stderr)
        return 1

    measures = resolve_measure(args.tier, args.measure)
    run_id_base = args.run_id_base if args.run_id_base is not None else int(time.time()) & 0xFFFFF
    run_counter = 0
    if args.results_dir is not None:
        results_root = args.results_dir.resolve()
    else:
        host_results_mount = args.host_results_mount.resolve()
        if host_results_mount.is_dir():
            results_root = host_results_mount
            print(f"using host-shared results dir: {results_root}", flush=True)
        else:
            results_root = (root / "results").resolve()
            print(
                f"host-shared results dir not mounted at {host_results_mount}; "
                f"falling back to local results dir {results_root}",
                flush=True,
            )
    json_dir = results_root / "json"
    lat_dir = results_root / "lat_log"
    meta_dir = results_root / "meta"
    host_log_dir = results_root / "host_log"
    summary_csv = results_root / "runs.csv"
    json_dir.mkdir(parents=True, exist_ok=True)
    meta_dir.mkdir(parents=True, exist_ok=True)
    host_log_dir.mkdir(parents=True, exist_ok=True)
    if args.write_lat_log:
        lat_dir.mkdir(parents=True, exist_ok=True)

    units = discover_units(iolog_dir)
    if args.unit:
        requested = set(args.unit)
        units = [unit for unit in units if unit.unit in requested]

    if not units:
        print("no workload units matched the requested selection", file=sys.stderr)
        return 1

    scaled_note = f" scaled={args.ssd_size_mb}mb" if args.scaled else ""
    print(
        f"running tier={args.tier} cap={args.cap}{scaled_note} scheme={args.scheme} "
        f"measure={','.join(measures)} units={len(units)} target={args.target}",
        flush=True,
    )

    for unit in units:
        print(f"== unit {unit.unit} ==", flush=True)

        if not args.skip_fill:
            run(fio_fill_cmd(args), args.dry_run)

        # Reset stats counters before warmup so the full unit (warmup + measured) is captured.
        if not args.no_femu_stats:
            femu_flip(args.nvme_dev, FEMU_STATS_RESET, dry_run=args.dry_run)

        if not args.skip_warmup:
            warmup_job = f"{args.scheme}_{args.tier}_{unit.unit}_warmup"
            run(fio_replay_cmd(args, warmup_job, unit.warmup, None, None), args.dry_run)
            if not args.dry_run:
                append_summary(
                    summary_csv, args.scheme, args.tier, unit.unit, "warmup", unit.warmup, None
                )

        for phase, iolog_path in iter_phases(unit, measures):
            run_id = run_id_base + run_counter
            run_counter += 1
            stats_file = f"stats_{run_id}.json"

            timestamp = datetime.now().strftime("%Y%m%d-%H%M%S")
            json_path = json_dir / f"{args.scheme}_{args.tier}_{unit.unit}_{phase}_{timestamp}.json"
            lat_log_prefix = (
                lat_dir / f"{args.scheme}_{args.tier}_{unit.unit}_{phase}_{timestamp}"
                if args.write_lat_log
                else None
            )
            meta_path = meta_dir / f"{args.scheme}_{args.tier}_{unit.unit}_{phase}_{timestamp}.json"
            host_log_path = host_log_dir / f"{args.scheme}_{args.tier}_{unit.unit}_{phase}_{timestamp}.stdout.log"
            job_name = f"{args.scheme}_{args.tier}_{unit.unit}_{phase}"
            metadata = {
                "timestamp": timestamp,
                "scheme": args.scheme,
                "build_label": args.build_label,
                "tier": args.tier,
                "unit": unit.unit,
                "phase": phase,
                "target": args.target,
                "cap": args.cap,
                "scaled": args.scaled,
                "ssd_size_mb": args.ssd_size_mb,
                "replay_time_scale": args.replay_time_scale,
                "ioengine": args.ioengine,
                "iodepth": args.iodepth,
                "fill_size": args.fill_size,
                "fill_bs": args.fill_bs,
                "fill_iodepth": args.fill_iodepth,
                "repetition_id": args.repetition_id,
                "iolog_path": str(iolog_path),
                "json_path": str(json_path),
                "lat_log_prefix": "" if lat_log_prefix is None else str(lat_log_prefix),
                "meta_path": str(meta_path),
                "host_log_path": str(host_log_path),
                "femu_run_id": run_id,
                "femu_stats_file": stats_file,
            }
            if not args.dry_run:
                write_metadata(meta_path, metadata)

            replay_cmd = fio_replay_cmd(args, job_name, iolog_path, json_path, lat_log_prefix)
            run(
                replay_cmd,
                args.dry_run,
                env=os.environ.copy(),
                stdout_path=host_log_path,
            )

            # Dump stats after the measured replay completes.
            if not args.no_femu_stats:
                femu_flip(args.nvme_dev, FEMU_STATS_DUMP, cdw11=run_id, dry_run=args.dry_run)

            if not args.dry_run:
                append_summary(
                    summary_csv, args.scheme, args.tier, unit.unit, phase, iolog_path, json_path,
                    femu_run_id=run_id,
                )

    print("completed workload set run", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
